// Copies the bundled web fonts (SIL OFL 1.1) out of @fontsource-variable
// into media/fonts and generates media/fonts/fonts.css.
// Run with: npm run fonts   (only needed when the font selection changes)
import { readFileSync, writeFileSync, copyFileSync, mkdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'media', 'fonts');

const FAMILIES = [
  { pkg: 'eb-garamond', subsets: ['latin', 'latin-ext', 'greek', 'greek-ext'] },
  { pkg: 'source-sans-3', subsets: ['latin', 'latin-ext'] },
  { pkg: 'inter', subsets: ['latin', 'latin-ext'] },
  { pkg: 'playfair-display', subsets: ['latin', 'latin-ext'] },
  { pkg: 'jetbrains-mono', subsets: ['latin', 'latin-ext'] },
];

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'licenses'), { recursive: true });

let css = '/* Generated by scripts/build-fonts.mjs. Fonts: SIL Open Font License 1.1, see ./licenses */\n';
for (const { pkg, subsets } of FAMILIES) {
  const dir = join(root, 'node_modules', '@fontsource-variable', pkg);
  copyFileSync(join(dir, 'LICENSE'), join(out, 'licenses', `${pkg}.txt`));
  for (const sheet of ['wght.css', 'wght-italic.css']) {
    const src = readFileSync(join(dir, sheet), 'utf8');
    for (const block of src.split(/(?=\/\* )/)) {
      const name = block.match(/\/\* (\S+) \*\//)?.[1];
      if (!name) continue;
      const subset = subsets.find((s) => name === `${pkg}-${s}-wght-normal` || name === `${pkg}-${s}-wght-italic`);
      if (!subset) continue;
      const file = block.match(/url\(\.\/files\/([^)]+)\)/)[1];
      copyFileSync(join(dir, 'files', file), join(out, file));
      css += block.replace('./files/', './').trim() + '\n\n';
    }
  }
}
writeFileSync(join(out, 'fonts.css'), css);
console.log('fonts.css written');
